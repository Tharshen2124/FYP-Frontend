import { localDateParam } from "@/lib/date"

import type { HistoryWeek } from "../_types"

// ─── helpers ──────────────────────────────────────────────────────────────────

function h(hour: number, min = 0) {
  return hour * 60 + min
}

function isoMonday(weeksAgo: number): string {
  // Today: 2026-06-09 (Tuesday) → this week's Monday = 2026-06-08
  const base = new Date(2026, 5, 8) // Jun 8 2026
  base.setDate(base.getDate() - weeksAgo * 7)
  // localDateParam, not toISOString — `base` is local midnight, so the UTC date is the
  // previous day anywhere east of UTC. See API_CONTRACT.md §0.
  return localDateParam(base)
}

function weekLabel(iso: string): string {
  const start = new Date(iso + "T00:00:00")
  const end = new Date(start)
  end.setDate(start.getDate() + 6)
  const fmt = (d: Date) =>
    `${d.getDate()} ${d.toLocaleString("default", { month: "short" })}`
  return `${fmt(start)} – ${fmt(end)}`
}

// ─── mock weeks ───────────────────────────────────────────────────────────────

const week = (
  weeksAgo: number
): Pick<HistoryWeek, "id" | "label" | "weekStart"> => {
  const ws = isoMonday(weeksAgo)
  return { id: `week-${weeksAgo}`, weekStart: ws, label: weekLabel(ws) }
}

